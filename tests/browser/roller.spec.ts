import { test, expect } from '@playwright/test';
test('panel rolls, sends fixed results to chat, and restores empty branches', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('Let the dice decide.')).toBeVisible();
  await page.screenshot({ path: 'test-results/desktop-empty.png', fullPage: true });
  await page.getByLabel('Choose your dice').fill('d20+5');
  await page.getByRole('button', { name: '↑ Advantage', exact: true }).click();
  await page.getByPlaceholder('e.g. Stealth check').fill('Stealth check');
  await page.getByPlaceholder('—', { exact: true }).fill('15');
  await page.getByRole('button', { name: 'Roll the dice', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Roll the dice', exact: true })).toBeEnabled();
  const result = await page.locator('.total').innerText();
  expect(Number(result)).toBeGreaterThanOrEqual(6);
  expect(Number(result)).toBeLessThanOrEqual(25);
  await expect(page.locator('.result-details .pip')).toHaveCount(2);
  await expect(page.locator('.result-details .dropped')).toHaveCount(1);
  await expect(page.getByText('1 roll queued for chat')).toBeVisible();
  await page.screenshot({ path: 'test-results/desktop-result.png', fullPage: true });
  await page.getByText('Developer chat simulator · local preview only').click();
  await page.getByLabel('Simulated chat message').fill('I sneak past the guard.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.locator('.dev-chat pre')).toContainText(`= ${result}`);
  await expect(page.locator('.queue')).toHaveCount(0);
  await page.getByRole('button', { name: 'Simulate empty branch' }).click();
  await expect(page.getByText('Let the dice decide.')).toBeVisible();
  expect(errors).toEqual([]);
});
test('mobile fits, rejects bad inputs, and runs chat commands', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto('/');
  await page.getByLabel('Choose your dice').fill('101d6');
  await page.getByRole('button', { name: 'Roll the dice', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('100 dice');
  await expect(page.locator('.total')).toHaveCount(0);
  await page.getByLabel('Choose your dice').fill('4d6kh3');
  await page.getByLabel('Include in my next chat message').uncheck();
  await page.getByRole('button', { name: 'Roll the dice', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Roll the dice', exact: true })).toBeEnabled();
  await expect(page.locator('.result-details .pip')).toHaveCount(4);
  await expect(page.locator('.queue')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mobile-result.png', fullPage: true });
  await page.getByText('Developer chat simulator · local preview only').click();
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await expect(page.locator('.dev-chat pre')).toContainText('Stealth: d20+5 (advantage)');
  await expect(page.locator('.dev-chat pre')).toContainText('DC 15');
});
